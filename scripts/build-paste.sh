#!/usr/bin/env bash
# Concatenates db/migrations/*.sql (in order) into database_to_paste.sql, the
# single file that is pasted into the Supabase SQL editor for a fresh project.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/database_to_paste.sql"
{
  echo "-- NWS Commerce - database schema"
  echo "-- GENERATED by scripts/build-paste.sh from db/migrations. Do not edit by hand."
  echo "-- Paste into the Supabase SQL editor of a NEW project and run once."
  echo
  for f in "$ROOT"/db/migrations/*.sql; do
    echo
    echo "-- ======================================================================"
    echo "-- $(basename "$f")"
    echo "-- ======================================================================"
    cat "$f"
  done
} > "$OUT"
echo "wrote $(basename "$OUT") ($(wc -l < "$OUT" | tr -d ' ') lines)"
